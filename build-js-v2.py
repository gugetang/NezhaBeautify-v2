#!/usr/bin/env python3
"""Build NezhaBeautify-v2.js (script-src version) from NezhaBeautify-v2.html.

Usage: python3 build-js-v2.py
Reads NezhaBeautify-v2.html in the same directory and writes NezhaBeautify-v2.js.
The .js file is a self-contained IIFE: it injects the CSS + HTML nodes, then
runs the same inline script (CONFIG + logic, including the guardian mount and
the dynamic Globe.GL loader with unpkg -> jsdelivr fallback).

Unlike the old v1 builder, there is NO external <script src> tag to extract:
the v2 HTML deliberately has no external Globe.GL tag, because InjectContext
awaits each external script in document order and a CDN failure would wipe
the whole custom_code injection. Globe.GL is loaded by the JS itself.

That makes the project loadable from Nezha v2 custom_code with one line:
  <script src="https://cdn.jsdelivr.net/gh/gugetang/NezhaBeautify-v2@main/NezhaBeautify-v2.js"></script>
Config override (optional, before the script tag):
  <script>window.NezhaBeautifyConfig = { finance: { prices: {} } };</script>
Note: the HTML version is still the source of truth; do not edit the .js
by hand, edit NezhaBeautify-v2.html and rebuild.
"""
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE / "NezhaBeautify-v2.html"
DST = HERE / "NezhaBeautify-v2.js"

text = SRC.read_text(encoding="utf-8")

m_style = re.search(r"^<style>(.*?)</style>", text, re.S | re.M)
m_inline = re.findall(r"^<script>(.*?)</script>", text, re.S | re.M)
m_ext = re.search(r'^<script\s+src="([^"]+)"></script>', text, re.M)
if not m_style or len(m_inline) != 1:
    sys.exit(
        f"unexpected structure: style={bool(m_style)} "
        f"inline_scripts={len(m_inline)}"
    )
if m_ext:
    sys.exit(
        "unexpected external <script src> in v2 HTML: "
        f"{m_ext.group(1)} (v2 must load Globe.GL dynamically, see README)"
    )

css = m_style.group(1).strip("\n")
# HTML nodes: between </style> and the first <script>
html = text[m_style.end() : text.find("<script>", m_style.end())].strip()
main_js = m_inline[0].strip("\n")

header = """// NezhaBeautify v2 — script-src version, generated from NezhaBeautify-v2.html
// Generated by build-js-v2.py — do not edit by hand, edit NezhaBeautify-v2.html and rebuild.
// Load from Nezha v2 custom_code with one line:
//   <script src="https://cdn.jsdelivr.net/gh/gugetang/NezhaBeautify-v2@main/NezhaBeautify-v2.js"></script>
// Optional config override, before that line:
//   <script>window.NezhaBeautifyConfig = { finance: { prices: {} } };</script>
(function () {
  'use strict';
  // Avoid double injection when custom_code is re-applied in the same page.
  // Note: the v2 guardian inside the main script also re-attaches nodes if
  // InjectContext disposes them, so this guard only stops a second full run.
  if (document.getElementById('welcome-bubble-container')) return;
  var CSS = %s;
  var HTML = %s;
  function inject() {
    if (!document.getElementById('nezha-beautify-v2-style')) {
      var st = document.createElement('style');
      st.id = 'nezha-beautify-v2-style';
      st.textContent = CSS;
      document.head.appendChild(st);
    }
    var tmp = document.createElement('div');
    tmp.innerHTML = HTML;
    while (tmp.firstChild) document.body.appendChild(tmp.firstChild);
  }
  function run() {
    inject();
%s
  }
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', run);
  } else {
    run();
  }
})();
""" % (
    json.dumps(css, ensure_ascii=False),
    json.dumps(html, ensure_ascii=False),
    main_js,
)

DST.write_text(header, encoding="utf-8")
print(f"wrote {DST} ({DST.stat().st_size} bytes)")
